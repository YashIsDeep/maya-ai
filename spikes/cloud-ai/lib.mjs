import { parseEnv } from "node:util";
import { costOf, ENVELOPE, MODELS, PRICES_AS_OF, PRICES_SOURCE, TARGET_USD_PER_TASK } from "./pricing.mjs";

export function loadKey({ env, envFileText }) {
  const fromEnvironment = env.MAYA_CLOUD_AI_API_KEY?.trim();
  if (fromEnvironment) return fromEnvironment;
  if (typeof envFileText === "string") {
    const fromFile = parseEnv(envFileText).MAYA_CLOUD_AI_API_KEY?.trim();
    if (fromFile) return fromFile;
  }
  return null;
}

export function redact(text, key) {
  if (!key) return text;
  return text.split(key).join("[redacted]");
}

export function checkResponse(model, json) {
  if (
    typeof json?.model !== "string" ||
    (json.model !== model &&
      !(json.model.startsWith(model + "-") && /^\d{8}$/.test(json.model.slice(model.length + 1))))
  ) {
    return `unexpected model ${String(json?.model)}`;
  }
  const usage = json.usage;
  if (
    !usage ||
    typeof usage !== "object" ||
    !Number.isInteger(usage.input_tokens) ||
    usage.input_tokens < 0 ||
    !Number.isInteger(usage.output_tokens) ||
    usage.output_tokens < 0
  ) {
    return "missing usage";
  }
  return null;
}

export function summarize(model, runs) {
  const taskTotals = runs.map((run) => {
    const input = run.reduce((total, usage) =>
      total + (usage.input_tokens ?? 0) +
        (usage.cache_creation_input_tokens ?? 0) +
        (usage.cache_read_input_tokens ?? 0), 0);
    const output = run.reduce((total, usage) => total + (usage.output_tokens ?? 0), 0);
    const cost = run.reduce((total, usage) => total + costOf(model, usage), 0);
    return { input, output, cost };
  });
  const mean = (key) => taskTotals.reduce((total, task) => total + task[key], 0) / taskTotals.length;
  const costs = taskTotals.map(({ cost }) => cost);
  return {
    model,
    runs: runs.length,
    meanInput: mean("input"),
    meanOutput: mean("output"),
    meanCost: mean("cost"),
    minCost: Math.min(...costs),
    maxCost: Math.max(...costs),
  };
}

export function chooseDefaultModel(summaries, target) {
  return summaries.find(({ meanCost }) => meanCost <= target)?.model ?? null;
}

export function renderReport({ generatedAt, mode, runs, summaries = [] }) {
  const estimateRows = MODELS.map((model) =>
    `| ${model} | US$${costOf(model, ENVELOPE).toFixed(4)} |`,
  ).join("\n");
  const defaultModel = mode === "live" ? chooseDefaultModel(summaries, TARGET_USD_PER_TASK) : null;
  const status = mode === "live"
    ? `Measured on the Claude API: ${runs} runs of the reference task per model.`
    : "Not measured: dry run, no API calls were made.";
  const measured = mode === "dry-run"
    ? "Not measured yet. The default model is chosen by the rule in cloud-ai.md §5 once measured."
    : [
        "| Model | Runs | Mean input tokens | Mean output tokens | Mean cost | Min cost | Max cost | Mean within target |",
        "|---|---|---|---|---|---|---|---|",
        ...summaries.map(({ model, runs: modelRuns, meanInput, meanOutput, meanCost, minCost, maxCost }) =>
          `| ${model} | ${modelRuns} | ${Math.round(meanInput)} | ${Math.round(meanOutput)} | US$${meanCost.toFixed(4)} | US$${minCost.toFixed(4)} | US$${maxCost.toFixed(4)} | ${meanCost <= TARGET_USD_PER_TASK ? "yes" : "no"} |`,
        ),
        "",
        "The reference task is smaller than production prompts; compare the mean tokens with the envelope above (cloud-ai.md §5, limits of the fixture).",
        "",
        defaultModel
          ? `**Default model for the spike:** ${String.fromCharCode(96)}${defaultModel}${String.fromCharCode(96)} (the first of Sonnet 5, then Haiku 4.5, whose mean measured cost is within the target).`
          : "**Default model for the spike:** none. No measured model is within the target; the owner decides in SP-08.",
      ].join("\n");

  return [
    "# Cloud AI cost per task: measurements",
    "",
    `Generated by ${String.fromCharCode(96)}spikes/cloud-ai/measure.mjs${String.fromCharCode(96)} on ${generatedAt} (${mode}). Do not edit by hand; rerun the script.`,
    "Method and decisions: [cloud-ai.md](cloud-ai.md).",
    "",
    `**Status:** ${status}`,
    "**Target:** at most US$0.05 per reference task (docs/DECISIONS.md, 2026-09-26).",
    `**Prices:** Claude API standard prices as of ${PRICES_AS_OF} (${PRICES_SOURCE}).`,
    "",
    "## Published-price estimate (12,000 input and 2,000 output tokens per task)",
    "",
    "| Model | Estimated cost per task |",
    "|---|---|",
    estimateRows,
    "",
    "## Measured",
    "",
    measured,
    "",
  ].join("\n");
}
