export function describe([id, title, tags, goal, blueprint, deps, done, notes]) {
  return [
    `**Goal.** ${goal}`,
    `**Blueprint.** ${blueprint}`,
    `**Depends on.** ${deps.length ? deps.join(", ") : "none"}`,
    `**Done when.**\n${done.map((d) => `- ${d}`).join("\n")}`,
    `**Notes.** ${notes || "none"}`,
    `_Process: docs/AGENTIFY_PROCESS.md_`,
  ].join("\n\n");
}

// Every dependency exists, and there are no cycles.
const byId = new Map(tasks.map((t) => [t[0], t]));
const state = new Map();
const visit = (id, from) => {
  if (!byId.has(id)) throw new Error(`${from} depends on unknown ${id}`);
  if (state.get(id) === 1) throw new Error(`dependency cycle through ${id}`);
  if (state.get(id) === 2) return;
  state.set(id, 1);
  for (const d of byId.get(id)[5]) visit(d, id);
  state.set(id, 2);
};
for (const [id] of tasks) visit(id, id);

if (!process.argv.includes("--create")) {
  for (const t of tasks) console.log(`[${t[0]}] ${t[1]}  (${t[2].join(",")})  ← ${t[5].join(", ") || "-"}`);
  console.log(`${tasks.length} tasks, dependencies OK`);
} else {
  const API = process.env.AGENTIFY_API ?? "http://127.0.0.1:2712/api";
  const headers = { Origin: new URL(API).origin, "Content-Type": "application/json" };
  const get = async (path) => (await fetch(API + path, { headers })).json();
  const wf = (await get("/workflows")).find((w) => w.name === "Maya Build");
  if (!wf) throw new Error("Maya Build workflow not found; run setup-workflow.mjs first");
  const existing = new Set((await get("/tasks")).map((t) => t.title));
  for (const t of tasks) {
    const title = `[${t[0]}] ${t[1]}`;
    if (existing.has(title)) { console.log("exists ", title); continue; }
    const res = await fetch(`${API}/tasks`, {
      method: "POST", headers,
      body: JSON.stringify({ workflowId: wf.id, title, description: describe(t), repoPath: "C:\\code\\maya", baseBranch: "main", tags: t[2] }),
    });
    console.log(res.ok ? "created" : `FAILED ${res.status} ${await res.text()}`, title);
  }
}
